`;
}

function human(c) {
  const v = c.value;
  if (c.unit === 'seconds') {
    if (v % 3600 === 0) return `${v / 3600} h`;
    if (v % 60 === 0) return `${v / 60} min`;
    return `${v} s`;
  }
  if (c.unit === 'milliseconds') return `${v / 1000} s`;
  if (c.unit === 'meters') return `${v} m`;
  if (c.unit === 'bytes') return `${v.toLocaleString('en-US')} bytes`;
  if (c.unit === 'pixels') return `${v} px`;
  if (c.unit === 'percent') return `${v}%`;
  return `${v}${c.unit === 'count' ? '' : ` ${c.unit}`}`;
}

function generateContractsDoc() {
  const docPath = 'docs/CONTRACTS.md';
  let doc = read(docPath);
  const authLabel = { user: 'person', public: 'none', cron: 'cron secret' };
  const endpointRows = operations().map(({ path: p, method, op }) =>
    `| \`${method.toUpperCase()} ${p}\` | \`${op.operationId}\` | ${op['x-owner']} | ${authLabel[authOf(op)]} | ${op.summary.replace(/\|/g, '\\|')} |`,
  );
  const endpoints = ['| Endpoint | operationId | Owner | Sign-in | Does |', '| --- | --- | --- | --- | --- |', ...endpointRows].join('\n');
  const eventRows = Object.entries(events.events).map(([name, ev]) =>
    `| \`${name}\` | \`${events.channels[ev.channel].topic}\` | ${ev.to} | ${ev.push ? `${ev.push.body}${ev.push.interruptionLevel === 'time-sensitive' ? ' (time sensitive)' : ''}` : 'No push'} | ${ev.description} |`,
  );
  const eventsTable = ['| Event | Channel | To | Lock screen text | Sent when |', '| --- | --- | --- | --- | --- |', ...eventRows].join('\n');
  const constRows = Object.entries(constants).map(([name, c]) => `| \`${name}\` | ${human(c)} | ${c.description} |`);
  const constTable = ['| Constant | Value | Meaning |', '| --- | --- | --- |', ...constRows].join('\n');
  for (const [key, table] of [['endpoints', endpoints], ['events', eventsTable], ['constants', constTable]]) {
    const re = new RegExp(`(<!-- BEGIN GENERATED: ${key} -->\\n)[\\s\\S]*?(<!-- END GENERATED: ${key} -->)`);
    if (!re.test(doc)) throw new Error(`${docPath} is missing the ${key} markers`);
    doc = doc.replace(re, `$1${table}\n$2`);
  }
  write(docPath, doc);
}

