function generateEventsTs() {
  const catalog = Object.entries(events.events).map(([name, ev]) => {
    const push = ev.push
      ? `{ body: ${JSON.stringify(ev.push.body)}, category: '${ev.push.category}', interruptionLevel: '${ev.push.interruptionLevel}', sound: '${ev.push.sound}', collapseId: '${ev.push.collapseId}', threadId: '${ev.push.threadId}' }`
      : 'null';
    return `  '${name}': {\n    channel: '${ev.channel}',\n    to: ${JSON.stringify(ev.to)},\n    push: ${push},\n  },`;
  });
  return `${HEADER_TS('contracts/events.json')}// Every event goes over Realtime to a private channel (event name = type, payload = the event),
// and as an APNs push when it has one. Payloads carry only the type plus a match or room ID.
import type { GlowEvent, GlowEventType } from './openapi/types.gen';

/** The private channel only this person can join. IDs are lowercased to match the policy. */
export const userTopic = (userId: string): string => \`user:\${userId.toLowerCase()}\`;
/** The private channel for people with an open check-in in this room. */
export const roomTopic = (roomId: string): string => \`room:\${roomId.toLowerCase()}\`;

export type PushInterruptionLevel = 'passive' | 'active' | 'time-sensitive';
export type PushSpec = {
  readonly body: string;
  readonly category: string;
  readonly interruptionLevel: PushInterruptionLevel;
  readonly sound: string;
  readonly collapseId: string;
  readonly threadId: string;
};
export type EventSpec = {
  readonly channel: 'user' | 'room';
  readonly to: string;
  readonly push: PushSpec | null;
};

export const eventCatalog = {
${catalog.join('\n')}
} as const satisfies Record<GlowEventType, EventSpec>;

/** The push categories the app registers. */
export const pushCategories = ${JSON.stringify([...new Set(Object.values(events.events).filter((e) => e.push).map((e) => e.push.category))]).replace(/"/g, "'")} as const;

export type ApnsRequest = {
  /** The JSON body: aps plus the event's own fields, nothing else (P1, P6). */
  readonly payload: {
    readonly aps: {
      readonly alert: { readonly body: string };
      readonly sound: string;
      readonly category: string;
      readonly 'thread-id': string;
      readonly 'interruption-level': PushInterruptionLevel;
    };
  } & GlowEvent;
  /** The apns-collapse-id header. */
  readonly collapseId: string;
  readonly interruptionLevel: PushInterruptionLevel;
};

/** The APNs request for an event, or null when the event has no push. */
export function apnsRequestFor(event: GlowEvent): ApnsRequest | null {
  const spec: PushSpec | null = eventCatalog[event.type].push;
  if (!spec) return null;
  const fill = (template: string): string =>
    template
      .replace('{matchId}', 'matchId' in event ? event.matchId : '')
      .replace('{roomId}', 'roomId' in event ? event.roomId : '');
  return {
    payload: {
      aps: {
        alert: { body: spec.body },
        sound: spec.sound,
        category: spec.category,
        'thread-id': fill(spec.threadId),
        'interruption-level': spec.interruptionLevel,
      },
      ...event,
    },
    collapseId: fill(spec.collapseId),
    interruptionLevel: spec.interruptionLevel,
  };
}
`;
}

