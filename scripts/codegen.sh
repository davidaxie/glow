# 4. The Swift client.
build_generator() {
  local dir="$CACHE/swift-openapi-generator-$GENERATOR_VERSION"
  local bin="$dir/.build/release/swift-openapi-generator"
  if [ ! -x "$bin" ]; then
    command -v swift >/dev/null || die "Swift is required for the Swift client (or pass --no-swift locally)."
    say "building swift-openapi-generator $GENERATOR_VERSION (once, into $CACHE)"
    mkdir -p "$CACHE"
    curl -sSfL "https://github.com/apple/swift-openapi-generator/archive/refs/tags/$GENERATOR_VERSION.tar.gz" \
      -o "$CACHE/generator.tar.gz"
    tar -xzf "$CACHE/generator.tar.gz" -C "$CACHE"
    rm -f "$CACHE/generator.tar.gz"
    (cd "$dir" && swift build -c release --product swift-openapi-generator >&2)
  fi
  printf '%s' "$bin"
}

