// ------------------------------------------------------------------------------ Swift
const ACRONYMS = new Set(['TTL', 'URL', 'QR', 'ID', 'JPEG']);
function swiftName(name, unit) {
  const words = name.split('_');
  const parts = words.map((w, i) => {
    if (i === 0) return w.toLowerCase();
    if (ACRONYMS.has(w)) return w;
    return w[0] + w.slice(1).toLowerCase();
  });
  let out = parts.join('');
  const suffix = { meters: 'Meters', pixels: 'Pixels', percent: 'Percent', bytes: 'Bytes', years: 'Years' }[unit];
  if (suffix && !out.endsWith(suffix)) out += suffix;
  return out;
}

function generateConstantsSwift() {
  const lines = Object.entries(constants).map(([name, c]) => {
    let type = 'Int';
    let value = String(c.value);
    if (c.unit === 'seconds') type = 'TimeInterval';
    if (c.unit === 'milliseconds') { type = 'TimeInterval'; value = String(c.value / 1000); }
    if (c.unit === 'meters') { type = 'Double'; value = c.value.toFixed(1); }
    const unitNote = c.unit === 'milliseconds' ? ' In seconds.' : '';
    return `    /// ${c.description}${unitNote} (\`${name}\`)\n    public static let ${swiftName(name, c.unit)}: ${type} = ${value}`;
  });
  return `${HEADER_SWIFT('contracts/constants.json')}
import Foundation

/// Shared numbers from contracts/constants.json. Durations are TimeInterval seconds.
public enum GlowConstants {
${lines.join('\n\n')}
}
`;
}

const swiftCase = (name) => name.split('.').map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1))).join('');

