#!/usr/bin/env bash
# Owner: A2. Generates every client, type and constant from contracts/.
#
#   scripts/codegen.sh            check the contracts, then regenerate everything (CI runs this,
#                                 then fails if git shows any change)
#   scripts/codegen.sh --verify   also compile the generated Swift and TypeScript on their own
#   scripts/codegen.sh --no-swift skip the Swift client (machines without Swift only, never CI)
#
# Inputs:  contracts/openapi.yaml, contracts/events.json, contracts/constants.json, and the local
#          database (only for database.ts, when it's running).
# Outputs (never hand-edit them):
#   server/src/contracts/openapi/        TypeScript types and zod schemas (@hey-api/openapi-ts)
#   server/src/contracts/operations.ts   the route helper's registry, one entry per operationId
#   server/src/contracts/constants.ts    constants
#   server/src/contracts/events.ts       channels, event catalog and APNs payloads
#   server/src/contracts/database.ts     Supabase table and function types (supabase gen types)
#   server/src/contracts/index.ts        barrel
#   ios/Packages/GlowKit/Sources/APIClient/Generated/   Swift client and types
#                                        (swift-openapi-generator), GlowConstants.swift, GlowEvents.swift
#   supabase/tests/database/000_constants.test.sql      DB constants must match constants.json
#   docs/CONTRACTS.md                    the tables between the GENERATED markers
#
# Needs Node 24 with `pnpm install` done (for @hey-api/openapi-ts and yaml), and Swift 5.10 or
# newer (Xcode on macOS, the runner's Swift on Ubuntu). swift-openapi-generator is downloaded
# once into $GLOW_CODEGEN_CACHE (default ~/.cache/glow-codegen) and built there.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

GENERATOR_VERSION="1.14.2"   # apple/swift-openapi-generator
RUNTIME_VERSION="1.13.3"     # apple/swift-openapi-runtime (what the generated code imports)
URLSESSION_VERSION="1.4.0"   # apple/swift-openapi-urlsession (the app's transport)
CACHE="${GLOW_CODEGEN_CACHE:-${XDG_CACHE_HOME:-$HOME/.cache}/glow-codegen}"

TS_OUT="server/src/contracts"
SWIFT_OUT="ios/Packages/GlowKit/Sources/APIClient/Generated"
SWIFT_EXCLUDED_TAGS="dev cron admin web"

VERIFY=0
SWIFT=1
for arg in "$@"; do
  case "$arg" in
    --verify) VERIFY=1 ;;
    --no-swift) SWIFT=0 ;;
    -h | --help) sed -n '2,26p' "$0"; exit 0 ;;
    *) echo "codegen: unknown option $arg" >&2; exit 2 ;;
  esac
done

say() { printf 'codegen: %s\n' "$*" >&2; }
die() { printf 'codegen: %s\n' "$*" >&2; exit 1; }

command -v node >/dev/null || die "node is required (see .nvmrc)."
[ -x node_modules/.bin/openapi-ts ] || die "run pnpm install first (needs @hey-api/openapi-ts)."

if [ "$(uname -s)" = "Darwin" ] && [ -z "${DEVELOPER_DIR:-}" ] && [ -d /Applications/Xcode.app ]; then
  # xcode-select may point at the Command Line Tools; the generator needs a full toolchain.
  export DEVELOPER_DIR=/Applications/Xcode.app/Contents/Developer
fi

TMP="$(mktemp -d "${TMPDIR:-/tmp}/glow-codegen.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

# ---------------------------------------------------------------------------------------------
# The Node half: contract checks and the small generators. Kept in this file so codegen has no
# other source files to own.
# ---------------------------------------------------------------------------------------------
cat > "$TMP/codegen.mjs" <<'JS'
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.env.GLOW_ROOT;
const require = createRequire(path.join(ROOT, 'package.json'));
const YAML = require('yaml');

const mode = process.argv[2];
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const write = (p, text) => {
  const full = path.join(ROOT, p);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, text);
};

const spec = YAML.parse(read('contracts/openapi.yaml'));
const events = JSON.parse(read('contracts/events.json'));
const constants = JSON.parse(read('contracts/constants.json')).constants;

const METHODS = ['get', 'post', 'put', 'patch', 'delete'];
const SERVER_ONLY_TAGS = ['admin', 'cron', 'dev', 'web'];
const HEADER_TS = (src) => `// Generated by scripts/codegen.sh from ${src}. Do not edit.\n`;
const HEADER_SWIFT = (src) =>
  `// Generated by scripts/codegen.sh from ${src}. Do not edit.\n// swiftlint:disable all\n// swiftformat:disable all\n`;

const errors = [];
const fail = (msg) => errors.push(msg);

function resolve(ref) {
  if (!ref.startsWith('#/')) throw new Error(`external $ref not supported: ${ref}`);
  return ref.slice(2).split('/').reduce((o, k) => o?.[k], spec);
}
const refName = (ref) => ref.split('/').pop();
const deref = (x) => (x && x.$ref ? deref(resolve(x.$ref)) : x);

function operations() {
  const out = [];
  for (const [p, item] of Object.entries(spec.paths)) {
    for (const method of METHODS) {
      const op = item[method];
      if (!op) continue;
      const params = [...(item.parameters ?? []), ...(op.parameters ?? [])].map(deref);
      out.push({ path: p, method, op, params });
    }
  }
  return out;
}

function authOf(op) {
  const sec = op.security ?? spec.security ?? [];
  if (sec.length === 0) return 'public';
  if (sec.some((s) => 'cronSecret' in s)) return 'cron';
  return 'user';
}

// ------------------------------------------------------------------------------ checks
function check() {
  const knownTags = new Set(spec.tags.map((t) => t.name));
  const seen = new Set();
  for (const { path: p, method, op, params } of operations()) {
    const where = `${method.toUpperCase()} ${p}`;
    if (!op.operationId) fail(`${where}: no operationId`);
    if (seen.has(op.operationId)) fail(`${where}: duplicate operationId ${op.operationId}`);
    seen.add(op.operationId);
    if (!/^[A-E][0-9]$/.test(op['x-owner'] ?? '')) fail(`${where}: x-owner must be an agent ID`);
    if (!op.tags?.length || op.tags.some((t) => !knownTags.has(t))) fail(`${where}: unknown or missing tag`);
    const statuses = Object.keys(op.responses ?? {});
    if (statuses.includes('403')) fail(`${where}: declares 403. Not allowed is 404 (P11).`);
    if (authOf(op) !== 'public' && !statuses.includes('401')) fail(`${where}: signed-in operation without 401`);
    const pathParams = params.filter((x) => x.in === 'path');
    if (pathParams.length && authOf(op) !== 'public' && !statuses.includes('404'))
      fail(`${where}: has path IDs but no 404 (P11)`);
    for (const name of [...p.matchAll(/\{([^}]+)\}/g)].map((m) => m[1])) {
      if (!pathParams.some((x) => x.name === name)) fail(`${where}: path parameter {${name}} isn't declared`);
    }
    if (!op.tags.some((t) => SERVER_ONLY_TAGS.includes(t))) checkPrivacy(op, where);
  }
  checkEvents();
  checkConstants();
}

// P1: what an app receives never names anyone else. Field names that would carry another
// person's identity or anyone's location are refused in every app-facing response, and every
// object there must be closed (additionalProperties: false).
const FORBIDDEN = new Set([
  'userId', 'userIds', 'senderId', 'recipientId', 'viewerId', 'otherUserId', 'ownerId',
  'email', 'phone', 'latitude', 'longitude', 'lat', 'lng', 'accuracy', 'coordinates',
  'location', 'lastName', 'fullName',
]);
const ALLOWED_ONLY_IN = {
  firstName: ['MyProfile', 'MatchSummary', 'MatchDetail'],
  birthdate: ['MyProfile'],
  gender: ['MyProfile'],
  showMe: ['MyProfile'],
  viewerCode: ['MyProfile'],
};

function checkPrivacy(op, where) {
  for (const [status, resp] of Object.entries(op.responses ?? {})) {
    if (!/^2/.test(status)) continue;
    const json = deref(resp).content?.['application/json'];
    if (json?.schema) walk(json.schema, json.schema.$ref ? refName(json.schema.$ref) : '(inline)', new Set(), where);
  }
}

function walk(schema, owner, visiting, where) {
  if (schema.$ref) {
    const name = refName(schema.$ref);
    if (visiting.has(name)) return;
    visiting.add(name);
    walk(resolve(schema.$ref), name, visiting, where);
    visiting.delete(name);
    return;
  }
  for (const key of ['oneOf', 'anyOf', 'allOf']) for (const s of schema[key] ?? []) walk(s, owner, visiting, where);
  if (schema.items) walk(schema.items, owner, visiting, where);
  if (schema.type === 'object' || schema.properties) {
    if (schema.additionalProperties !== false) fail(`${where}: ${owner} must set additionalProperties: false`);
    for (const [prop, sub] of Object.entries(schema.properties ?? {})) {
      if (FORBIDDEN.has(prop)) fail(`${where}: ${owner}.${prop} could identify or locate someone (P1, P2)`);
      if (ALLOWED_ONLY_IN[prop] && !ALLOWED_ONLY_IN[prop].includes(owner))
        fail(`${where}: ${owner}.${prop} is only allowed in ${ALLOWED_ONLY_IN[prop].join(', ')} (P1)`);
      walk(sub, owner, visiting, where);
    }
  }
}

function checkEvents() {
  const schemas = spec.components.schemas;
  const names = Object.keys(events.events);
  const mapping = schemas.GlowEvent?.discriminator?.mapping ?? {};
  if (JSON.stringify(Object.keys(mapping).sort()) !== JSON.stringify([...names].sort()))
    fail('events.json and openapi GlowEvent.discriminator.mapping list different events');
  if (JSON.stringify([...(schemas.GlowEventType?.enum ?? [])].sort()) !== JSON.stringify([...names].sort()))
    fail('events.json and openapi GlowEventType list different events');
  for (const [name, ev] of Object.entries(events.events)) {
    const schema = schemas[ev.payloadSchema];
    if (!schema) { fail(`${name}: payload schema ${ev.payloadSchema} isn't in openapi.yaml`); continue; }
    if (mapping[name] !== `#/components/schemas/${ev.payloadSchema}`) fail(`${name}: GlowEvent mapping points elsewhere`);
    if (schema.additionalProperties !== false) fail(`${ev.payloadSchema}: must set additionalProperties: false`);
    const props = Object.keys(schema.properties ?? {});
    if (props.some((p) => !['type', 'matchId', 'roomId'].includes(p)))
      fail(`${ev.payloadSchema}: payloads carry only type plus a match or room ID (P1)`);
    if (JSON.stringify(schema.properties?.type?.enum) !== JSON.stringify([name]))
      fail(`${ev.payloadSchema}: type must be exactly "${name}"`);
    if (!events.channels[ev.channel]) fail(`${name}: unknown channel ${ev.channel}`);
    if (ev.push) {
      if (/[{}]/.test(ev.push.body)) fail(`${name}: push body must be fixed text, never filled in (P6)`);
      if (!['passive', 'active', 'time-sensitive'].includes(ev.push.interruptionLevel))
        fail(`${name}: bad interruptionLevel`);
      const filled = ev.push.collapseId.replace(/\{(matchId|roomId)\}/g, '00000000-0000-0000-0000-000000000000');
      if (filled.length > 64) fail(`${name}: collapseId is longer than 64 bytes`);
      for (const k of ['collapseId', 'threadId']) {
        for (const m of ev.push[k].matchAll(/\{([^}]+)\}/g)) {
          if (!props.includes(m[1])) fail(`${name}: push.${k} uses {${m[1]}}, which the payload doesn't have`);
        }
      }
    }
  }
}

const UNITS = ['seconds', 'milliseconds', 'count', 'meters', 'characters', 'pixels', 'percent', 'bytes', 'years'];
function checkConstants() {
  for (const [name, c] of Object.entries(constants)) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(name)) fail(`constant ${name}: use UPPER_SNAKE_CASE`);
    if (typeof c.value !== 'number' || !Number.isInteger(c.value)) fail(`constant ${name}: value must be an integer`);
    if (!UNITS.includes(c.unit)) fail(`constant ${name}: unknown unit ${c.unit}`);
    if (!c.description) fail(`constant ${name}: needs a description`);
  }
}

// ------------------------------------------------------------------------------ TypeScript
function zodForParam(schema, required) {
  const s = deref(schema);
  let expr;
  if (s.enum) expr = `z.enum(${JSON.stringify(s.enum)})`;
  else if (s.type === 'integer') {
    expr = 'z.coerce.number().int()';
    if (s.minimum !== undefined) expr += `.min(${s.minimum})`;
    if (s.maximum !== undefined) expr += `.max(${s.maximum})`;
  } else if (s.type === 'string' && s.format === 'uuid') expr = 'z.uuid()';
  else if (s.type === 'string' && s.format === 'date-time') expr = 'z.iso.datetime()';
  else if (s.type === 'string') {
    expr = 'z.string()';
    if (s.pattern) expr += `.regex(new RegExp(${JSON.stringify(s.pattern)}))`;
    if (s.minLength !== undefined) expr += `.min(${s.minLength})`;
    if (s.maxLength !== undefined) expr += `.max(${s.maxLength})`;
  } else throw new Error(`unsupported parameter schema ${JSON.stringify(s)}`);
  return required ? expr : `${expr}.optional()`;
}

function schemaRef(schema, zodExports, where) {
  if (!schema?.$ref) throw new Error(`${where}: JSON bodies must be a $ref to components.schemas`);
  const name = `z${refName(schema.$ref)}`;
  if (!zodExports.has(name)) throw new Error(`${where}: ${name} isn't in the generated zod schemas`);
  return `s.${name}`;
}

function generateOperations(zodExports) {
  const lines = [];
  const info = [];
  for (const { path: p, method, op, params } of operations()) {
    const id = op.operationId;
    const isWeb = op.tags.includes('web');
    const entry = [`    method: '${method.toUpperCase()}',`, `    path: '${p}',`, `    auth: '${authOf(op)}',`];
    for (const where of ['path', 'query']) {
      const list = params.filter((x) => x.in === where);
      if (!list.length) continue;
      const fields = list.map((x) => `      ${x.name}: ${zodForParam(x.schema, where === 'path' || x.required)},`);
      entry.push(`    ${where === 'path' ? 'params' : 'query'}: z.object({`, ...fields, '    }),');
    }
    if (op.requestBody) {
      const body = deref(op.requestBody);
      const json = body.content?.['application/json'];
      if (!json) throw new Error(`${id}: only JSON request bodies are supported`);
      const expr = schemaRef(json.schema, zodExports, id);
      entry.push(`    body: ${body.required ? expr : `${expr}.optional()`},`);
    }
    if (op['x-max-body-bytes']) entry.push(`    maxBodyBytes: ${op['x-max-body-bytes']},`);
    entry.push('    responses: {');
    for (const [status, raw] of Object.entries(op.responses)) {
      if (!/^\d{3}$/.test(status)) continue;
      const resp = deref(raw);
      const content = resp.content ?? {};
      let spec;
      if (Object.keys(content).length === 0) spec = 'null';
      else if (isWeb || !content['application/json']) spec = "'raw'";
      else spec = schemaRef(content['application/json'].schema, zodExports, `${id} ${status}`);
      entry.push(`      ${status}: ${spec},`);
    }
    entry.push('    },');
    lines.push(`  ${id}: {`, ...entry, '  },');
    info.push(
      `  ${id}: { owner: '${op['x-owner']}', tags: ${JSON.stringify(op.tags).replace(/"/g, "'")}, summary: ${JSON.stringify(op.summary)} },`,
    );
  }
  return `${HEADER_TS('contracts/openapi.yaml')}// One entry per operationId, in the shape of OperationDef (server/src/server/http/operation.ts).
// Path and query values arrive as strings, so their schemas coerce. JSON bodies and replies use
// the zod schemas generated from components.schemas. 'raw' means the handler sends its own
// Response (images, HTML, the link file); null means no body.
import { z } from 'zod';
import type { OperationDef } from '@/server/http/operation';
import * as s from './openapi/zod.gen';

export const operations = {
${lines.join('\n')}
} as const satisfies Record<string, OperationDef>;

export type ContractOperations = typeof operations;
export type ContractOperationId = keyof ContractOperations;

/** Who builds each operation, from x-owner, and its tags and summary. */
export const operationInfo = {
${info.join('\n')}
} as const satisfies Record<ContractOperationId, { owner: string; tags: readonly string[]; summary: string }>;
`;
}

