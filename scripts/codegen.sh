if (mode === 'check') {
  check();
  if (errors.length) {
    for (const e of errors) console.error(`codegen: contract check: ${e}`);
    process.exit(1);
  }
} else if (mode === 'tidy-swift') {
  // swift-openapi-generator 1.14 splits the types into Types+*.swift files, each with the same
  // public imports, and Swift 6 warns about every public import a file doesn't use publicly.
  // Merging them back into one Types.swift gives one import block that is used, so the client
  // builds with no warnings.
  const dir = path.join(ROOT, 'ios/Packages/GlowKit/Sources/APIClient/Generated');
  const order = [
    'Types.swift', 'Types+Components.swift', 'Types+Components+Schemas.swift',
    'Types+Components+Parameters.swift', 'Types+Components+RequestBodies.swift',
    'Types+Components+Responses.swift', 'Types+Components+Headers.swift', 'Types+Operations.swift',
  ];
  const present = fs.readdirSync(dir).filter((f) => /^Types.*\.swift$/.test(f));
  const unknown = present.filter((f) => !order.includes(f));
  if (unknown.length) throw new Error(`unexpected generated files: ${unknown.join(', ')}`);
  let head = null;
  const bodies = [];
  for (const file of order.filter((f) => present.includes(f))) {
    const lines = fs.readFileSync(path.join(dir, file), 'utf8').split('\n');
    let i = 0;
    const isHead = (l) => /^\/\/(?!\/)/.test(l) || /^(@\w+(\(\w+\))? )*(public |internal )?import /.test(l);
    while (i < lines.length && isHead(lines[i])) i++;
    const fileHead = lines.slice(0, i).join('\n');
    if (head === null) head = fileHead;
    else if (fileHead !== head) throw new Error(`${file} has a different header or imports; can't merge`);
    bodies.push(lines.slice(i).join('\n').replace(/\s+$/, ''));
    if (file !== 'Types.swift') fs.rmSync(path.join(dir, file));
  }
  fs.writeFileSync(path.join(dir, 'Types.swift'), `${head}\n${bodies.join('\n\n')}\n`);
} else if (mode === 'swift-tags') {
  const excluded = (process.env.SWIFT_EXCLUDED_TAGS ?? '').split(/\s+/);
  process.stdout.write(spec.tags.map((t) => t.name).filter((t) => !excluded.includes(t)).join(','));
} else if (mode === 'generate') {
  const zodSource = read('server/src/contracts/openapi/zod.gen.ts');
  const zodExports = new Set([...zodSource.matchAll(/^export const (z\w+)/gm)].map((m) => m[1]));
